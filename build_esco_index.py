skills_set = set()

# Если у тебя есть скачанный локальный файл ESCO (skills_ru.csv > 50 КБ), скрипт включит его
if os.path.exists("skills_ru.csv") and os.path.getsize("skills_ru.csv") > 1024:
    print("Обнаружен локальный файл skills_ru.csv, загрузка...")
    try:
        df = pd.read_csv("skills_ru.csv")
        target_col = "preferredLabel" if "preferredLabel" in df.columns else df.columns[0]
        for val in df[target_col].dropna():
            cleaned = re.sub(r"\(.*?\)", "", str(val)).strip().lower()
            if 2 <= len(cleaned) <= 60:
                skills_set.add(cleaned)
        print(f"Загружено {len(skills_set)} навыков из CSV.")
    except Exception as e:
        print(f"Ошибка чтения CSV: {e}")

# Дополняем эталонным каталогом
skills_set.update([s.strip().lower() for s in TAXONOMY_CATALOG])
final_skills = sorted(list(skills_set))

print(f"2. Итоговое число компетенций для индексации: {len(final_skills)}")
print("3. Векторизация базы через rubert-tiny2...")
embeddings = embedder.encode(final_skills, batch_size=256, show_progress_bar=True, normalize_embeddings=True)

# Сохранение артефактов
with open("esco_skills.json", "w", encoding="utf-8") as f:
    json.dump(final_skills, f, ensure_ascii=False, indent=2)

np.save("esco_embeddings.npy", embeddings.astype(np.float32))

