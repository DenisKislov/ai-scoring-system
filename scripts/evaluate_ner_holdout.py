"""Audit frozen NER splits and evaluate the provided model without retraining.

Only prepared DocBin files are read. Original PDF directories are never read.
Near matches are candidates for manual lineage review, not proof of duplicates.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sys
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from spacy.tokens import DocBin  # noqa: E402
from spacy.training import Example  # noqa: E402
from spacy.vocab import Vocab  # noqa: E402
from spacy.scorer import Scorer  # noqa: E402

from scorer.config import algorithm_manifest  # noqa: E402
from scorer.corpus import resume_text_of, vacancy_text_of  # noqa: E402
from scorer.privacy import professional_text  # noqa: E402
from scorer.ner_skills import _load, ner_status  # noqa: E402
from scripts.benchmark_real_data import evaluate  # noqa: E402


def tokens(text):
    text = unicodedata.normalize('NFKC', professional_text(text)).casefold().replace('ё', 'е')
    return re.findall(r'\w+', text)


def grams(text):
    words = tokens(text)
    return set(zip(*(words[offset:] for offset in range(5))))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--training-root', type=Path, required=True)
    parser.add_argument('--benchmark-dir', type=Path, default=ROOT/'data/benchmark')
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    model = _load()
    if model is None:
        parser.error('NER model unavailable')
    groups = {}
    sources = {}
    for split in ('train', 'dev', 'test'):
        file = args.training_root/(split+'.spacy')
        groups[split] = list(DocBin().from_disk(file).get_docs(Vocab()))
        sources[split] = hashlib.sha256(file.read_bytes()).hexdigest()
    identities = {name: {hashlib.sha256(' '.join(tokens(doc.text)).encode()).hexdigest()
                         for doc in docs} for name, docs in groups.items()}
    duplicates = {a+'_'+b: len(identities[a] & identities[b])
                  for a, b in [('train', 'dev'), ('train', 'test'), ('dev', 'test')]}
    if any(duplicates.values()):
        parser.error('Duplicate text across training/evaluation splits')
    examples = [Example(model(doc.text), doc) for doc in groups['test']]
    scores = Scorer().score(examples)
    training_grams = [grams(doc.text) for doc in groups['train'] + groups['dev']]
    overlap = {}
    disjoint_rows = {}
    for filename, adapt in [('superjob_dataset.json', vacancy_text_of),
                            ('dataset_resume.json', resume_text_of)]:
        rows = json.loads((args.benchmark_dir/filename).read_text())
        similarities = []
        for row in rows:
            query = grams(adapt(row))
            similarities.append(max((len(query & sample)/len(query | sample)
                                     if query | sample else 0.0 for sample in training_grams), default=0.0))
        # This conservative diagnostic subset excludes matches at Jaccard >= .5.
        kept = [row for row, similarity in zip(rows, similarities) if similarity < .5]
        disjoint_rows[filename] = kept
        overlap[filename] = {'documents': len(rows),
            'similarity_at_least_0_8': sum(value >= .8 for value in similarities),
            'excluded_at_0_5': len(rows)-len(kept), 'retained': len(kept)}
    diagnostic = evaluate(disjoint_rows['superjob_dataset.json'],
                          disjoint_rows['dataset_resume.json'], ranking_inputs='extracted')
    report = {'date': datetime.now(timezone.utc).isoformat(),
              'algorithm': algorithm_manifest(), 'ner_status': ner_status(),
              'source_docbin_sha256': sources,
              'split_documents': {name:len(docs) for name,docs in groups.items()},
              'exact_cross_split_duplicates': duplicates,
              'test_span_metrics': {key:scores[key] for key in ('ents_p','ents_r','ents_f')},
              'benchmark_overlap_with_train_dev': overlap,
              'disjoint_diagnostic': diagnostic,
              'limitations': [
                  'Entity references were generated by dictionary/alias matching, without independent expert verification.',
                  'Near text matches require manual review; text similarity is not identity proof.',
                  'The diagnostic subset excludes NER train/dev near matches, but the dictionary was historically adjusted on this benchmark.',
                  'This is not an independent real-world hiring evaluation.']}
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir/'ner_holdout.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({key:report[key] for key in ('split_documents','exact_cross_split_duplicates',
                        'test_span_metrics','benchmark_overlap_with_train_dev')},ensure_ascii=False,indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
